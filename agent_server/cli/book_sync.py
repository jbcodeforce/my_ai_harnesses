@app.command()
def stats(
    root: BookRoot,
    write: Annotated[bool, typer.Option("--write", help="Write measured values into the stats region.")] = False,
) -> None:
    """Measure counters from book.yml and compare with the stats region."""
    try:
        cfg = load(root)
    except (FileNotFoundError, ValueError) as exc:
        err_console.print(f"[bold red]✗ {exc}[/bold red]")
        raise typer.Exit(code=1)

    measured = measure(cfg)
    if not measured:
        console.print("[dim]No stats configured in book.yml.[/dim]")
        return

    table = Table(title=f"Stats — {cfg.name}")
    table.add_column("ID", style="cyan")
    table.add_column("Label")
    table.add_column("Count", justify="right")
    for m in measured:
        table.add_row(m.id, m.label, str(m.count))
    console.print(table)

    drift = compare_with_region(cfg, measured)
    if drift:
        for w in drift:
            console.print(f"  [yellow]DRIFT[/yellow]  {w}")
    else:
        console.print("[dim]Stats region is in sync.[/dim]")

    if write:
        try:
            apply_stats(cfg, measured)
            console.print("[bold green]✓ Stats region updated.[/bold green]")
        except (FileNotFoundError, ValueError) as exc:
            err_console.print(f"[bold red]✗ {exc}[/bold red]")
            raise typer.Exit(code=1)


