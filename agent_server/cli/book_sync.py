"""
cli/book_sync.py — Typer CLI wrapper over core/.

Commands
--------
  validate  Check book.yml and the book's files.
  init      Add book.yml, AGENTS.md and markers to an existing book.
  audit     Run all three checks (GitHub URLs, nav, versions).
  versions  Print the canonical version for each configured check.
  news      Collect commits since last sync and write a draft.
  apply     Apply a reviewed draft into the marked regions.
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Annotated, Optional

import typer
from rich.console import Console
from rich.table import Table

from core.audit import audit as run_audit, print_versions
from core.book import load, validate
from core.news import (
    apply_draft,
    collect_commits,
    get_sync_commit,
    group_by_section,
    write_draft,
)
from core.stats import apply_stats, compare_with_region, measure

app = typer.Typer(
    name="book-sync",
    help="Keep every book's docs accurate — audit, news, stats.",
    add_completion=False,
)
console = Console()
err_console = Console(stderr=True)

BookRoot = Annotated[
    Path,
    typer.Argument(
        help="Path to the book repository root (must contain book.yml).",
        exists=True,
        file_okay=False,
        dir_okay=True,
        resolve_path=True,
    ),
]


# ---------------------------------------------------------------------------
# validate
# ---------------------------------------------------------------------------

@app.command(name="validate")
def validate_cmd(
    root: BookRoot,
) -> None:
    """Check book.yml, referenced paths, markers, and regex patterns."""
    errors = validate(root)
    if errors:
        err_console.print(f"[bold red]✗ {len(errors)} error(s) in {root}:[/bold red]")
        for e in errors:
            err_console.print(f"  • {e}")
        raise typer.Exit(code=1)
    else:
        console.print(f"[bold green]✓ {root} — book.yml is valid[/bold green]")


