_BOOK_YML_TEMPLATE = """\
# Generated by book-sync init.  Edit by hand; tools never rewrite this file.
# See BOOK_STANDARD.md for the full schema.
schema: 1
name: {name}
repo:
  url: https://github.com/<owner>/{name}
  branch: main

paths:
  docs: docs
  mkdocs: mkdocs.yml
  index: docs/index.md
  # news: docs/news/index.md        # uncomment if you have a news page
  scratch: .context

# sections:                         # define path → section mappings for news
# ignore_commits:
#   - '^Merge '
#   - '(?i)^(typo|wip)\\b'
"""

_AGENTS_MD_TEMPLATE = """\
# {name}

<One sentence: what this book teaches and for whom.>

## Layout
- `docs/` MkDocs content (chapters listed in `mkdocs.yml`)
- `code/` samples, `e2e-demos/` larger demos (only if present)
- `.context/` gitignored scratch for agent drafts

## Contract
Machine-readable settings live in `book.yml`. Run `book-sync validate` after changing structure.

## Rules for agents
- Edit only between `<!-- book:... -->` markers when a tool owns the text.
- News is curated: summarize and group, never invent items, drop anything not traceable to a commit.
- Show a diff and wait for approval before committing.
- Python: use `uv`.
"""

_UPDATES_MARKERS = (
    "<!-- book:updates:start -->",
    "<!-- book:updates:end -->",
)

_SYNC_MARKER = "<!-- book:sync commit=HEAD date=1970-01 -->"


def _insert_updates_markers(index_path: Path, dry_run: bool) -> str:
    """Insert update markers into the index file if they are absent.

    Returns a human-readable description of what was done (or would be done).
    """
    text = index_path.read_text(encoding="utf-8") if index_path.exists() else ""
    start, end = _UPDATES_MARKERS
    if start in text and end in text:
        return "  updates markers already present — not changed"

    # Try to insert inside an existing admonition block.
    lines = text.splitlines(keepends=True)
    insert_after = -1
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith(("???", "!!!")):
            insert_after = i
            break

    if insert_after >= 0:
        marker_block = (
            f"    {start}\n"
            f"    {end}\n"
        )
        lines.insert(insert_after + 1, marker_block)
        new_text = "".join(lines)
        action = f"  inserted updates markers after admonition on line {insert_after + 1}"
    else:
        # Append a new admonition at the end of the file.
        new_text = text.rstrip("\n") + (
            "\n\n??? info \"Updates\"\n"
            f"    {start}\n"
            f"    {end}\n"
        )
        action = "  appended new 'Updates' admonition with markers"

    if not dry_run:
        index_path.write_text(new_text, encoding="utf-8")
    return action


@app.command()
def init(
    root: BookRoot,
    dry_run: Annotated[bool, typer.Option("--dry-run", help="Show what would change, but write nothing.")] = False,
) -> None:
    """Add book.yml, AGENTS.md, and markers to an existing book (non-destructive)."""
    root = Path(root)
    name = root.name
    actions: list[str] = []

    # book.yml
    book_yml = root / "book.yml"
    if book_yml.exists():
        actions.append("  book.yml already exists — not changed")
    else:
        content = _BOOK_YML_TEMPLATE.format(name=name)
        if not dry_run:
            book_yml.write_text(content, encoding="utf-8")
        actions.append("  wrote book.yml (fill in repo.url and branch)")

    # AGENTS.md
    agents_md = root / "AGENTS.md"
    if agents_md.exists():
        actions.append("  AGENTS.md already exists — not changed")
    else:
        content = _AGENTS_MD_TEMPLATE.format(name=name)
        if not dry_run:
            agents_md.write_text(content, encoding="utf-8")
        actions.append("  wrote AGENTS.md (fill in description)")

    # .context/ directory
    scratch = root / ".context"
    if scratch.exists():
        actions.append("  .context/ already exists — not changed")
    else:
        if not dry_run:
            scratch.mkdir(parents=True, exist_ok=True)
        actions.append("  created .context/")

    # updates markers in index.md
    index_path = root / "docs" / "index.md"
    if index_path.exists():
        action = _insert_updates_markers(index_path, dry_run)
        actions.append(action)
    else:
        actions.append("  docs/index.md not found — skipping markers (create the file first)")

    prefix = "[yellow]DRY RUN[/yellow] " if dry_run else ""
    console.print(f"{prefix}[bold]book-sync init[/bold] in [cyan]{root}[/cyan]:")
    for a in actions:
        console.print(a)

    if not dry_run:
        console.print("\n[bold green]Done.[/bold green]  Edit book.yml, then run [cyan]book-sync validate[/cyan].")
    else:
        console.print("\n[dim]Run without --dry-run to apply.[/dim]")


