@app.command()
def news(
    root: BookRoot,
    since: Annotated[Optional[str], typer.Option("--since", help="Start from this commit SHA instead of the sync marker.")] = None,
) -> None:
    """Collect commits since the last sync and write a draft to .context/news-draft.md."""
    try:
        cfg = load(root)
    except (FileNotFoundError, ValueError) as exc:
        err_console.print(f"[bold red]✗ {exc}[/bold red]")
        raise typer.Exit(code=1)

    since_commit = since or get_sync_commit(cfg)
    if since_commit is None:
        err_console.print(
            "[yellow]No sync marker found and --since not given.  "
            "Pass --since <commit> to start from a specific commit.[/yellow]"
        )
        raise typer.Exit(code=1)

    commits = collect_commits(cfg, since_commit=since_commit)
    if not commits:
        console.print("[dim]No new commits since the last sync.[/dim]")
        return

    newest = commits[0].sha
    groups = group_by_section(cfg, commits)
    draft_path = write_draft(cfg, groups, since_commit, newest_commit=newest)

    total = sum(len(v) for v in groups.values())
    console.print(
        f"[bold green]Draft written:[/bold green] {draft_path}  "
        f"({total} commit(s) across {len(groups)} section(s))"
    )
    console.print("[dim]Review the draft, then run [cyan]book-sync apply[/cyan] to publish it.[/dim]")


