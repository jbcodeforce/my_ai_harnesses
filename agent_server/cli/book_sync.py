@app.command()
def apply(
    root: BookRoot,
    draft: Annotated[Optional[Path], typer.Option("--draft", help="Path to the draft to apply.")] = None,
    region: Annotated[str, typer.Option("--region", help="Marked region to update.")] = "news-site",
) -> None:
    """Apply a reviewed draft into the marked regions of the sync file."""
    try:
        cfg = load(root)
    except (FileNotFoundError, ValueError) as exc:
        err_console.print(f"[bold red]✗ {exc}[/bold red]")
        raise typer.Exit(code=1)

    draft_path = draft or (cfg.scratch_path() / "news-draft.md")

    try:
        apply_draft(cfg, draft_path, region=region)
    except (FileNotFoundError, ValueError) as exc:
        err_console.print(f"[bold red]✗ {exc}[/bold red]")
        raise typer.Exit(code=1)

    console.print(f"[bold green]✓ Applied[/bold green] {draft_path} → {cfg.sync_file()}")


