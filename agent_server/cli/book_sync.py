@app.command()
def versions(
    root: BookRoot,
) -> None:
    """Print the canonical version for each configured versions entry."""
    try:
        cfg = load(root)
    except (FileNotFoundError, ValueError) as exc:
        err_console.print(f"[bold red]✗ {exc}[/bold red]")
        raise typer.Exit(code=1)

    rows = print_versions(cfg)
    if not rows:
        console.print("[dim]No versions configured in book.yml.[/dim]")
        return

    table = Table(title=f"Versions — {cfg.name}")
    table.add_column("ID", style="cyan")
    table.add_column("Canonical")
    table.add_column("Source file", style="dim")
    for r in rows:
        table.add_row(r["id"], r["canonical"], r["source_file"])
    console.print(table)


