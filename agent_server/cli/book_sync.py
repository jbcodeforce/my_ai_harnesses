@app.command()
def audit(
    root: BookRoot,
    fix: Annotated[bool, typer.Option("--fix", help="Rewrite fixable problems in-place.")] = False,
) -> None:
    """Run all three checks: GitHub URLs, mkdocs nav, and version strings."""
    try:
        cfg = load(root)
    except (FileNotFoundError, ValueError) as exc:
        err_console.print(f"[bold red]✗ {exc}[/bold red]")
        raise typer.Exit(code=1)

    results = run_audit(cfg, fix=fix)
    total_errors = 0
    for r in results:
        icon = "[green]✓[/green]" if r.ok else "[red]✗[/red]"
        console.print(f"{icon} [bold]{r.check}[/bold]")
        for e in r.errors:
            err_console.print(f"    [red]ERROR[/red]  {e}")
            total_errors += 1
        for w in r.warnings:
            console.print(f"    [yellow]WARN[/yellow]   {w}")
        for f in r.fixed:
            console.print(f"    [cyan]FIXED[/cyan]  {f}")

    if total_errors:
        raise typer.Exit(code=1)


